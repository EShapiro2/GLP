import re
def t(s):
    toks=re.findall(r"'[^']*'|[A-Z_][A-Za-z0-9_]*\??|[a-z][A-Za-z0-9_]*|-?\d+(?:\.\d+)?|[()\[\],|]|\s+",s)
    assert ''.join(toks)==s, (s,''.join(toks))
    return ''.join("var('%s')"%x if re.fullmatch(r"[A-Z_][A-Za-z0-9_]*\??",x) else x for x in toks)

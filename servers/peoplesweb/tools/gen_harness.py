"""Write a live harness for a contract's canonical platform: the four persons in one heap (live_ui/1), or one person alone, an agent of madGLP (live_person/3).

Usage: python3 -I gen_harness.py <platform.vglp> <outdir> <NAME>

The harness copies the platform, platform.vglp, beside itself, and the platform's types it needs; it runs each person as the apps' miniapp.glp runs theirs: the platform's agent and its dispatcher (vGLP, "The canonical compilation"), the host (the live server) being every person: in(Person, Grant) goes to that person's channel.  A platform whose agent reads a calendar (Stream(Integer)?) gets one per person, fed by the host's cal(Person, N).  The host's first act picks the agent: me(Person), one person alone, its platform's messages sent by send_to_net; or world, the four persons together, their networks joined by route4.
"""
import re, sys, os, shutil

plat, out, name = sys.argv[1:4]
src = open(plat, encoding='utf-8').read()

# The platform's type definitions, read with its comment lines taken out: a
# definition the compiler prints over several lines may hold a comment line
# between two of its alternatives, as Var does, and a comment that ends with a
# full stop would end the definition there.
decls = {}
for m in re.finditer(r'^([A-Z][A-Za-z]*(?:\([A-Z]\))?)\s*::=(.*?)\.\s*$', re.sub(r'^[ \t]*%.*\n', '', src, flags=re.M), re.M | re.S):
    decls.setdefault(m.group(1), m.group(0).strip())

sig = re.search(r'^exported procedure agent\((.*)\)\.\s*$', src, re.M).group(1)
seeds = ['Net', 'Output', 'Approval', 'Proposal', 'Class', 'Atom', 'Request', 'YesNo']
need, todo = [], list(seeds)
while todo:
    t = todo.pop()
    key = next((k for k in decls if k == t or k.startswith(t + '(')), None)
    if not key or key in need or t == 'Peer':
        continue
    need.append(key)
    todo += [r for r in re.findall(r'\b([A-Z][A-Za-z]*)\b', decls[key].split('::=', 1)[1]) if r != t]
types = '\n'.join(decls[k] for k in decls if k in need)


def split_top(s):
    outp, depth, buf = [], 0, ''
    for ch in s:
        if ch in '([': depth += 1
        if ch in ')]': depth -= 1
        if ch == ',' and depth == 0:
            outp.append(buf.strip()); buf = ''; continue
        buf += ch
    if buf.strip(): outp.append(buf.strip())
    return outp


# The agent call's arguments, by the exported signature: the peer, the network
# input and output, the calendar where the platform reads one, and the thread.
args = split_top(sig)
cal = 'Stream(Integer)?' in args


def agent_args(p, net_in, net_out, thread, k):
    got = []
    for a in args:
        if a == 'Peer?': got.append(p)
        elif a == 'Stream(Net)?': got.append(net_in)
        elif a == 'Stream(Net)': got.append(net_out)
        elif a == 'Stream(Integer)?': got.append(k)
        elif a == 'Stream(Output)': got.append(thread)
        # The environment atoms a deployment gives (vGLP, Section 5.4, "Speech-act
        # schemas as local specifications"): the demo deploys with none.
        elif a == 'List(Atom)?': got.append('[]')
        else: raise SystemExit(f'{name}: agent takes {a}, which this harness does not know')
    return ', '.join(got)


P, L = ['alice', 'bob', 'carol', 'dave'], 'ABCD'
ks = ', KA, KB, KC, KD' if cal else ''

head = f"""%% The live harness of the canonical CVA platform of {name} (platform.vglp,
%% as cascade.sh records it, copied beside this file): alice, bob, carol and
%% dave, each the platform's agent and its dispatcher, as the apps' miniapp.glp
%% runs them; the host (the live server) is every person{', and feeds each agent the day by cal(Person, N)' if cal else ''}.
%% Generated by gen_harness.py; the platform's types are copied.

"""

body = f"""
%% Question and Drawn restate the compiled platform's, as the apps' self.glp
%% restate them (programs/apps/*/self.glp): an import must agree with the
%% export, and Drawn's `_` is the compilation's own --- "every other drawn
%% value is typed _" (vGLP, Section 6.3, "The construct process"; the
%% restatements are on test/OPEN_TYPES).
Question ::= request_r(Request?) ; approval_w(Approval).
Drawn    ::= request_r(_) ; approval_w(_) ; output(List(Output)) ; Request ; YesNo.
Ask(Q)   ::= ask(Constant, Q).
HostAct  ::= me(Peer) ; world ; in(Peer, Input(Drawn)) ; cal(Peer, Integer) ; g(Input(Drawn)) ; cal(Integer).
HostIn   ::= [HostAct | HostIn].
Shown    ::= d(Peer, Draw(Drawn)) ; net(Sent(Cargo)).

imported procedure platform#agent({sig}, Stream(Ask(Question))).
imported procedure platform#dispatch(Stream(Ask(Question))?,
    PersonChannel(Drawn)?, Channel(Stream(Input(Drawn)), Stream(Output))).

%% The agent's initial goal, every agent's, agent(ch(_?,_),ch(_?,_)) (IGLP,
%% Implementation Notes, "Boot"): the host's acts are the first channel's
%% input, and the harness writes to the person itself, by send_to_user/1.
%% The host's first act says which agent this is: me(Person), one person
%% alone, whose network is the agent's (live_person/3); or world, the four
%% persons, their networks joined inside it (live_ui/1).
exported procedure agent(Channel(HostIn, Stream(Constant))?, Channel(Stream(Net), Stream(Net))?).
agent(ch(Ins, []), ch(N, [])) :- start(Ins?, N?).

procedure start(HostIn?, Stream(Net)?).
start([me(P) | Ins], N) :- ground(P?) | live_person(P?, Ins?, N?).
start([world | Ins], _) :- live_ui(Ins?).
start([_ | Ins], N) :- otherwise | start(Ins?, N?).

procedure live_ui(HostIn?).
live_ui(Ins) :-
    split4(Ins?, GA, GB, GC, GD{ks}),
"""
for p, x in zip(P, L):
    body += f"""    platform # agent({agent_args(p, f'In{x}?', f'Out{x}', f'T{x}', f'K{x}?')}, A{x}),
    platform # dispatch(A{x}?, ch(G{x}?, D{x}), M{x}),
    to_person(M{x}?, T{x}?),
    tag({p}, D{x}?, S{x}),
"""
body += """    merge(OutA?, OutB?, Net1),
    merge(OutC?, OutD?, Net2),
    merge(Net1?, Net2?, Net),
    route4(Net?, alice, InA, bob, InB, carol, InC, dave, InD, L),
    tag_net(L?, SN),
    merge(SA?, SB?, S1),
    merge(SC?, SD?, S2),
    merge(S1?, S2?, S3),
    merge(S3?, SN?, S),
    send_to_user(S?).

"""
if not cal:
    body += """procedure split4(HostIn?, PersonIn(Drawn), PersonIn(Drawn), PersonIn(Drawn), PersonIn(Drawn)).
split4([in(alice, G)|Ins], [G?|A?], B?, C?, D?) :- split4(Ins?, A, B, C, D).
split4([in(bob, G)|Ins], A?, [G?|B?], C?, D?) :- split4(Ins?, A, B, C, D).
split4([in(carol, G)|Ins], A?, B?, [G?|C?], D?) :- split4(Ins?, A, B, C, D).
split4([in(dave, G)|Ins], A?, B?, C?, [G?|D?]) :- split4(Ins?, A, B, C, D).
split4([_|Ins], A?, B?, C?, D?) :- otherwise | split4(Ins?, A, B, C, D).
"""
else:
    R = 'KA, KB, KC, KD'
    Rq = 'KA?, KB?, KC?, KD?'
    body += f"""procedure split4(HostIn?, PersonIn(Drawn), PersonIn(Drawn), PersonIn(Drawn), PersonIn(Drawn),
    Stream(Integer), Stream(Integer), Stream(Integer), Stream(Integer)).
split4([in(alice, G)|Ins], [G?|A?], B?, C?, D?, {Rq}) :- split4(Ins?, A, B, C, D, {R}).
split4([in(bob, G)|Ins], A?, [G?|B?], C?, D?, {Rq}) :- split4(Ins?, A, B, C, D, {R}).
split4([in(carol, G)|Ins], A?, B?, [G?|C?], D?, {Rq}) :- split4(Ins?, A, B, C, D, {R}).
split4([in(dave, G)|Ins], A?, B?, C?, [G?|D?], {Rq}) :- split4(Ins?, A, B, C, D, {R}).
split4([cal(alice, N)|Ins], A?, B?, C?, D?, [N?|KA?], KB?, KC?, KD?) :- split4(Ins?, A, B, C, D, {R}).
split4([cal(bob, N)|Ins], A?, B?, C?, D?, KA?, [N?|KB?], KC?, KD?) :- split4(Ins?, A, B, C, D, {R}).
split4([cal(carol, N)|Ins], A?, B?, C?, D?, KA?, KB?, [N?|KC?], KD?) :- split4(Ins?, A, B, C, D, {R}).
split4([cal(dave, N)|Ins], A?, B?, C?, D?, KA?, KB?, KC?, [N?|KD?]) :- split4(Ins?, A, B, C, D, {R}).
split4([_|Ins], A?, B?, C?, D?, {Rq}) :- otherwise | split4(Ins?, A, B, C, D, {R}).
"""
body += """
procedure tag(Peer?, PersonOut(Drawn)?, Stream(Shown)).
tag(N, [X|Xs], [d(N?, X?)|Ts?]) :- ground(N?) | tag(N?, Xs?, Ts).

procedure tag_net(Stream(Sent(Cargo))?, Stream(Shown)).
tag_net([X|Xs], [net(X?)|Ts?]) :- tag_net(Xs?, Ts).
tag_net([], []).

%% One person alone, any person, named as the host names it: live_person(Person,
%% HostIn, NetIn) runs the person's platform agent and its dispatcher, its
%% network input the agent's own; the platform's messages go out by
%% send_to_net, a cold call each to the person it names, and arrive on that
%% person's network input.  The host feeds the person g(Grant)""" + (' and cal(N)' if cal else '') + """.
procedure live_person(Peer?, HostIn?, Stream(Net)?).
live_person(P, Ins, NetIn) :- ground(P?) |
    """ + ('split_person(Ins?, G, K)' if cal else 'split_person(Ins?, G)') + f""",
    platform # agent({agent_args('P?', 'NetIn?', 'Out', 'T', 'K?')}, A),
    platform # dispatch(A?, ch(G?, D), M),
    to_person(M?, T?),
    tee_net(Out?, Net, L),
    send_to_net(Net?),
    tag(P?, D?, S),
    tag_net(L?, SN),
    merge(S?, SN?, S1),
    send_to_user(S1?).
"""
if cal:
    body += """
procedure split_person(HostIn?, PersonIn(Drawn), Stream(Integer)).
split_person([g(G)|Ins], [G?|Gs?], Ks?) :- split_person(Ins?, Gs, Ks).
split_person([cal(N)|Ins], Gs?, [N?|Ks?]) :- split_person(Ins?, Gs, Ks).
split_person([_|Ins], Gs?, Ks?) :- otherwise | split_person(Ins?, Gs, Ks).
"""
else:
    body += """
procedure split_person(HostIn?, PersonIn(Drawn)).
split_person([g(G)|Ins], [G?|Gs?]) :- split_person(Ins?, Gs).
split_person([_|Ins], Gs?) :- otherwise | split_person(Ins?, Gs).
"""
body += """
%% The agent's network output, passed on whole, each message noted as route4 notes it.
procedure tee_net(Stream(Net)?, Stream(Net), Stream(Sent(Cargo))).
tee_net([msg(To, M)|Ms], [msg(To?, M?)|Os?], Log?) :-
    ground(To?), ground(M?) |
    note(M?, To?, Log, Log1?),
    tee_net(Ms?, Os, Log1).
tee_net([], [], []).
"""

os.makedirs(out, exist_ok=True)
for stale in ['contract', 'trust.json', 'contract.glpw']:
    p = os.path.join(out, stale)
    if os.path.isdir(p): shutil.rmtree(p)
    elif os.path.exists(p): os.remove(p)
shutil.copy(plat, os.path.join(out, 'platform.vglp'))
open(os.path.join(out, 'self.glp'), 'w', encoding='utf-8', newline='\n').write(head + types + '\n' + body)
print(name, 'calendar' if cal else '', len(need), 'types')
